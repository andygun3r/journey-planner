export const SIGNALLING_CORRIDORS: Record<SignallingCorridorId, SignallingCorridor> =
  Object.fromEntries(CORRIDORS.map((c) => [c.id, c]));

/** Every corridor id, for route generation and tests. */
export const SIGNALLING_CORRIDOR_IDS = Object.keys(SIGNALLING_CORRIDORS);

export function namedSignallingCorridor(value: string | undefined): SignallingCorridor | undefined {
  if (!value) return undefined;
  return SIGNALLING_CORRIDORS[value.toLowerCase()];
}

/** Ordered CRS codes — the shape `resolveAreasForCorridor` and the renderer want. */
export function corridorStationCrs(corridor: SignallingCorridor): string[] {
  return corridor.stations.map((s) => s.crs);
}

/**
 * The corridor to offer on a station board.
 *
 * A station can sit on several corridors (Guildford is on three). The trunk
 * wins, so a Waterloo-bound passenger gets the main line rather than whichever
 * branch happens to be declared first.
 */
export function stationSignallingCorridor(crs: string): SignallingCorridor | undefined {
  const normalized = crs.toUpperCase();
  const onCorridor = Object.values(SIGNALLING_CORRIDORS).filter((corridor) =>
    corridor.stations.some((s) => s.crs === normalized),
  );
  return onCorridor.find((c) => !c.parentId) ?? onCorridor[0];
}
