/**
 * The corridors the signalling blueprint can draw.
 *
 * This file is the single source of truth for corridor shape. It used to be a
 * bare list of CRS codes, with everything else — station names, which stations
 * are junctions, which branches leave where, and what each branch page is
 * called — hardcoded separately inside the renderer and the branch route. Those
 * four copies drifted (14 branch links against 15 branch pages), so they now
 * all read from here instead.
 *
 * Station order is the drawing order: index 0 is the top of the diagram.
 * Real distance between stations comes from station_track_model_position at
 * render time, not from this file — see the renderer's mileage handling.
 */

export type SignallingCorridorId = string;

export interface CorridorStation {
  crs: string;
  /** Display name. Validated against the `station` table by the corridor test. */
  name: string;
  /** Draws a heavier tick and a full name rather than just the CRS. */
  junction?: boolean;
}

export interface CorridorBranch {
  /** Slug, and the /signalling/<id> route it links to. */
  id: SignallingCorridorId;
  /** The station on this corridor where the branch leaves. */
  atCrs: string;
  label: string;
  /** Which side of the diagram the spur hangs off. */
  side: "up" | "down";
}

export interface SignallingCorridor {
  id: SignallingCorridorId;
  title: string;
  shortTitle: string;
  stations: CorridorStation[];
  branches: CorridorBranch[];
  /** Set on branches: the corridor they leave from, for the "back to" link. */
  parentId?: SignallingCorridorId;
  /** The station on the parent corridor this one leaves from. */
  parentAtCrs?: string;
}

/**
 * Track Model's TRACK_ID → the name signallers actually use.
 *
 * NWR_TrackCentreLines has ASSET_ID, ELR, TRACK_ID, START, END and nothing
 * else — there is no field anywhere in the extract carrying a human name for a
 * running line. Track *count* and *extent* are therefore fully derived from the
 * data (see `etl track-sections`), but the names have to come from somewhere,
 * and this is that somewhere.
 *
 * Deliberately hand-written rather than inferred from the ID's shape: the
 * numbering looks systematic (1xxx down, 2xxx up, x100 fast, x200 slow) but a
 * confidently wrong label on a signalling diagram is worse than no label, so
 * anything not listed here falls back to `Line <id>` via trackRoleName().
 */
const TRACK_ROLE_NAMES: Record<string, string> = {
  "1100": "Down Fast",
  "2100": "Up Fast",
  "1200": "Down Slow",
  "2200": "Up Slow",
  "1300": "Down Local",
  "2300": "Up Local",
};

export function trackRoleName(trackId: string): string {
  return TRACK_ROLE_NAMES[trackId] ?? `Line ${trackId}`;
}

function s(crs: string, name: string, junction?: boolean): CorridorStation {
  return junction ? { crs, name, junction: true } : { crs, name };
}

